// Copies the compiled FlowLedgerAnchor ABI + bytecode into @flowledger/ledger,
// so the app and the browser verify page never depend on Hardhat at runtime.
// Usage: pnpm --filter @flowledger/contracts build && pnpm --filter @flowledger/contracts export-artifact
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const here = import.meta.dirname;
const artifact = JSON.parse(
  readFileSync(resolve(here, "../artifacts/contracts/FlowLedgerAnchor.sol/FlowLedgerAnchor.json"), "utf8")
);
const out = `// Generated by packages/contracts/scripts/export-artifact.mjs. Do not edit.
// Source: packages/contracts/contracts/FlowLedgerAnchor.sol (solc 0.8.28, optimizer 200, evm paris)

export const anchorAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const anchorBytecode = "${artifact.bytecode}" as const;
`;
writeFileSync(resolve(here, "../../ledger/src/anchor-artifact.ts"), out, "utf8");
console.log(`[contracts] exported ABI (${artifact.abi.length} entries) and bytecode to packages/ledger/src/anchor-artifact.ts`);
